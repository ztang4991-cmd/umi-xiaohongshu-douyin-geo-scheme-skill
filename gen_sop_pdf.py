def reg_font():
    for fp in ['C:/Windows/Fonts/msyh.ttc','C:/Windows/Fonts/simhei.ttf',
               'C:/Windows/Fonts/simsun.ttc',
               '/usr/share/fonts/truetype/wqy/wqy-microhei.ttc']:
        if os.path.exists(fp):
            try:
                pdfmetrics.registerFont(TTFont('ZH', fp))
                return 'ZH'
            except Exception:
                pass
    return 'Helvetica'

FONT = reg_font()

def S(name, **kw):
    return ParagraphStyle(name=name, fontName=FONT, **kw)

ST = {
    'cvt': S('cvt',fontSize=22,leading=28,alignment=TA_CENTER,
              textColor=colors.HexColor('#1a1a1a'),spaceAfter=10),
    'cvs': S('cvs',fontSize=13,leading=18,alignment=TA_CENTER,
              textColor=colors.HexColor('#555'),spaceAfter=6),
    'h1':  S('h1', fontSize=15,leading=20,spaceBefore=14,spaceAfter=8,
              textColor=colors.HexColor('#c0392b')),
    'h2':  S('h2', fontSize=12,leading=16,spaceBefore=10,spaceAfter=6,
              textColor=colors.HexColor('#2c3e50')),
    'h3':  S('h3', fontSize=10,leading=14,spaceBefore=8,spaceAfter=4,
              textColor=colors.HexColor('#555')),
    'bd':  S('bd', fontSize=9, leading=13,spaceAfter=5,alignment=TA_JUSTIFY),
    'bl':  S('bl', fontSize=9, leading=13,leftIndent=16,spaceAfter=4),
    'nt':  S('nt', fontSize=8, leading=12,textColor=colors.HexColor('#888')),
    'cl':  S('cl', fontSize=8, leading=11),
    'ch':  S('ch', fontSize=8, leading=11,textColor=colors.white),
}
HDR_C = colors.HexColor('#2c3e50')
ROW_C = colors.HexColor('#ecf0f1')
RED_C = colors.HexColor('#c0392b')

def P(t, st='bd'): return Paragraph(t, ST[st])
def H1(t): return Paragraph(t, ST['h1'])
def H2(t): return Paragraph(t, ST['h2'])
def H3(t): return Paragraph(t, ST['h3'])
def SP(n=0.3): return Spacer(1, n*cm)
def HR(): return HRFlowable(width='100%', thickness=1, color=RED_C, spaceAfter=6)

def mktbl(data, cw):
    t = Table(data, colWidths=cw)
    t.setStyle(TableStyle([
        ('BACKGROUND',    (0,0), (-1, 0), HDR_C),
        ('ROWBACKGROUNDS',(0,1), (-1,-1), [colors.white, ROW_C]),
        ('GRID',          (0,0), (-1,-1), 0.4, colors.HexColor('#bdc3c7')),
        ('VALIGN',        (0,0), (-1,-1), 'TOP'),
        ('TOPPADDING',    (0,0), (-1,-1), 4),
        ('BOTTOMPADDING', (0,0), (-1,-1), 4),
        ('LEFTPADDING',   (0,0), (-1,-1), 5),
        ('RIGHTPADDING',  (0,0), (-1,-1), 5),
    ]))
    return t

def HR_(cells): return [Paragraph(c, ST['ch']) for c in cells]
def RW(cells):  return [Paragraph(c, ST['cl']) for c in cells]

def shot_tbl(rows):
    hdr = HR_(['时段','镜头内容','拍摄手法（小白版）','配音/字幕','操作要点'])
    return mktbl([hdr]+[RW(r) for r in rows],
                 [1.3*cm, 3*cm, 4.8*cm, 4.7*cm, 2.7*cm])

def checklist(items):
    return [P('• '+i, 'bl') for i in items]

def fanwen(lines):
    return [H3('发布文案'), P('<br/>'.join(lines), 'bd'), SP(0.2)]

